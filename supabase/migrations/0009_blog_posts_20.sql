## Como a cárie se forma

Na nossa boca vivem bactérias que se alimentam dos açúcares e carboidratos que consumimos. Ao fazer isso, elas produzem ácidos que atacam o esmalte, a camada mais externa e dura do dente. Quando esse ataque acontece muitas vezes ao dia e a placa bacteriana não é removida, o esmalte vai perdendo minerais até se formar uma cavidade.

