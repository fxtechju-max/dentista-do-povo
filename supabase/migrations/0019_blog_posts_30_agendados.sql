## O que é a prótese protocolo

É uma prótese com todos os dentes de uma arcada, presa de forma fixa a implantes instalados no osso, geralmente de quatro a seis. O paciente não tira a prótese em casa: apenas o dentista consegue removê-la nas consultas de manutenção.

## Vantagens

- firmeza para mastigar, sorrir e falar sem medo da prótese soltar;
- melhora da mastigação em comparação com a dentadura;
- não cobre o céu da boca, o que melhora o paladar e o conforto;
- ajuda a preservar o osso na região dos implantes;
- devolve autoestima e qualidade de vida.

## Como é o tratamento

1. Avaliação clínica e exames de imagem, como a tomografia.
2. Planejamento da posição dos implantes.
3. Cirurgia para instalação dos implantes.
4. Em alguns casos, é possível colocar uma prótese provisória fixa logo nos primeiros dias, a chamada carga imediata. Em outros, aguarda-se a cicatrização.
5. Confecção e instalação da prótese definitiva.

## Quem pode fazer

É preciso ter boa saúde geral e quantidade de osso suficiente, ou fazer enxerto. Diabetes descontrolado e tabagismo aumentam o risco de complicações e precisam ser avaliados.

## Cuidados e higiene

A higiene é diferente da dentadura e muito importante:

- escove a prótese e a região onde ela encosta na gengiva;
- use escovas interdentais e fio dental próprio, passando por baixo da prótese;
- um irrigador oral pode ajudar;
- faça as consultas de manutenção, quando o dentista remove a prótese, limpa e confere os implantes.

